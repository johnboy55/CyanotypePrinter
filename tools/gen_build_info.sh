#!/bin/sh
# Writes MotorController_Mega/build_info.h with the current git branch and
# commit, so the Mega shows at boot exactly which code was flashed.
# Run automatically by the hooks in .githooks/ (enable once per clone with
#   git config core.hooksPath .githooks
# ) or by hand before compiling. The header is git-ignored.
root=$(git rev-parse --show-toplevel) || exit 0
branch=$(git rev-parse --abbrev-ref HEAD 2>/dev/null)
commit=$(git rev-parse --short HEAD 2>/dev/null)
date=$(git log -1 --format=%cd --date=format:%Y-%m-%d 2>/dev/null)
cat > "$root/MotorController_Mega/build_info.h" <<EOT
// Generated by tools/gen_build_info.sh -- do not edit, not committed.
#pragma once
#define BUILD_GIT_BRANCH "$branch"
#define BUILD_GIT_COMMIT "$commit"
#define BUILD_GIT_DATE   "$date"
EOT
